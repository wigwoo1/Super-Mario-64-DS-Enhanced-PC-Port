"""Generate typed native DEMO adapters from its source and original descriptors."""
import pathlib, re, struct, argparse
from boot_closure import COMMENT_OR_STRING
root = pathlib.Path(__file__).resolve().parents[2]
source = (root/'src/actors/daDemo_c.cpp').read_text()
rom = (root/'extracted/overlays/overlay_0002.bin').read_bytes()
symbols = {}
for line in (root/'config/arm9/overlays/ov002/symbols.txt').read_text().splitlines():
    m = re.match(r'(\S+) kind:function\([^)]*\) addr:0x([\da-f]+)', line)
    if m: symbols[m[1]] = int(m[2],16)
functions = {}
chunks = re.split(r'// @symbol (\S+)\s*', source)
for symbol, body in zip(chunks[1::2],chunks[2::2]):
    body = COMMENT_OR_STRING.sub(' ',body)
    m = re.search(r'(?:^|\n)\s*(?:extern\s+\s*)?(?:void|int|s32)\s+([\w:]+)\s*\(([^()]*)\)\s*\{', body)
    if m and symbol in symbols:
        params = []
        for p in m[2].split(','):
            p=p.strip()
            if p and p != 'void':
                typ = re.sub(r'\b\w+\s*$','',p).strip()
                if not typ: raise ValueError(p)
                params.append(typ)
        functions[symbols[symbol]] = (m[1],params)
init = (root/'src/unnamed/ov002/__sinit_ov002_02107370.c').read_text()
tables = {}
for m in re.finditer(r'data_ov002_(02110[e-f][\da-f]{2})\[\d+\]\.[xy]\s*=\s*data_ov002_([\da-f]+)',init):
    tables[int(m[2],16)] = 0 if m[1] in ('02110f34','02110f9c') else 1
for m in re.finditer(r'extern PMF3 data_ov002_([\da-f]+)\s*;',source): tables[int(m[1],16)] = 3
targets = {}
for descriptor, arity in tables.items():
    target, adjustment = struct.unpack_from('<II',rom,descriptor-0x020ad660)
    if adjustment: raise ValueError(f'unsupported adjustment {descriptor:x}')
    if target: targets.setdefault(target,set()).add(arity)
lines = ['// Generated by port/tools/demo_callbacks.py; typed adapters consume the recorded argument count.']
cases=[]
for target, arities in sorted(targets.items()):
    name,params=functions[target]
    # Original ldr/bx veneer preserves self in r0; its C void(void) spelling
    # cannot forward the receiver on x86. Adapt directly to the real callee.
    if target == 0x020f26d4:
        name,params=functions[0x020f2630]
    method='::' in name
    for arity in sorted(arities):
        args=['unsigned char *a0','int a1','int a2'] if arity==3 else (['int a0'] if arity==1 else [])
        actual=[]
        for i,typ in enumerate(params):
            idx=i if method else i-1
            value='self' if idx<0 else f'a{idx}'
            if idx>=arity: raise ValueError(f'{name} has more arguments than descriptor: {arity}')
            actual.append(f'({typ}){value}')
        call = f'((daDemo_c*)self)->{name}({", ".join(actual)})' if method else f'{name}({", ".join(actual)})'
        adapter=f'pc_demo_cb_{target:08x}_{arity}'
        trace = ''
        if target == 0x020f7bb8:
            trace = 'if (std::getenv("SM64DS_PC_TRACE")) std::fprintf(stderr,"[native DEMO curve] self=%p payload=%p args=%d,%d words=%08x,%08x\\n",self,a0,a1,a2,ReadUnalignedInt(a0),ReadUnalignedInt(a0+4)); '
        lines += [f'static void __fastcall {adapter}(void *self, void *unused'+(' ,'+', '.join(args) if args else '')+f') {{ {trace}(void){call}; }}']
        cases += [f'case 0x{target:08x}: if (arity == {arity}) return (uintptr_t)&{adapter}; break;'] if len(arities)==1 else []
    if len(arities)>1:
        cases += [f'case 0x{target:08x}: '+ ' '.join(f'if (arity=={a}) return (uintptr_t)&pc_demo_cb_{target:08x}_{a};' for a in sorted(arities))+' break;']
lines += ['static uintptr_t pc_demo_callback_address(uintptr_t address, unsigned arity) {',
          'if (address < 0x02004000 || address >= 0x02400000) return address;', 'switch(address) {', *cases, '}',
          'std::fprintf(stderr,"Unmapped DEMO callback %08x arity=%u\\n",(unsigned)address,arity); std::abort();', '}']
lines += ['static void pc_demo_rebase_resources() {']
declared = source + (root/'include/decl_common.h').read_text()
resource_tables = {0x0210b600:1,0x0210b604:1,0x0210b608:1,0x0210b60c:1,0x0210b610:1,
                   0x0210bcf0:13,0x0210bd24:13}
rebased = 0
for line in (root/'config/arm9/overlays/ov002/relocs.txt').read_text().splitlines():
    m=re.match(r'from:0x([\da-f]+) kind:load to:0x([\da-f]+) module:overlay\((\d+)\)',line)
    if not m: continue
    address,target,module=int(m[1],16),int(m[2],16),int(m[3])
    for base,count in resource_tables.items():
        if base <= address < base+count*4:
            target_name = f'data_ov{module:03d}_{target:08x}'
            if not re.search(r'extern[^;]*\b'+target_name+r'\b',declared):
                # local extern: opaque address of the eight-byte cartridge handle;
                # no shared header currently declares this relocation target.
                lines += [f'extern char {target_name}[];']
            lines += [f'*(void **)((char *)&data_ov002_{base:08x} + {address-base}) = (void *)&data_ov{module:03d}_{target:08x};']
            rebased += 1
lines += ['*(void **)&data_ov002_0210b604 = (void *)&data_ov009_02113c28;', '}']
arm=(root/'extracted/arm9_dec.bin').read_bytes()
arm_data={}
for line in (root/'config/arm9/symbols.txt').read_text().splitlines():
    m=re.match(r'(data_[\da-f]+) kind:data\([^)]*\) addr:0x([\da-f]+)',line)
    if m: arm_data[int(m[2],16)]=m[1]
curves=[]
for address,name in sorted(arm_data.items()):
    if not 0x0208751c <= address <= 0x02087740: continue
    count,points=struct.unpack_from('<II',arm,address-0x02004000)
    if 0<count<=256 and points in arm_data:
        curves.append((name,arm_data[points]))
lines += ['// Curve headers retain ROM addresses in +4; rebase their point arrays.', 'extern "C" {']
for name in sorted({name for pair in curves for name in pair}):
    lines += [f'extern unsigned char {name}[];']
lines += ['void pc_rebase_cutscene_curves() {']
for header,points in curves:
    lines += [f'*(void **)({header} + 4) = {points};']
lines += ['}', '}']
output=root/'port/hal/demo_callbacks.inc'
generated='\n'.join(lines)+'\n'
if not output.exists() or output.read_text()!=generated:
    output.write_text(generated)
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--map',type=pathlib.Path)
args=parser.parse_args()
if args.map:
    linked=args.map.read_text()
    for target,arities in targets.items():
        for arity in arities:
            if f'?pc_demo_cb_{target:08x}_{arity}@@' not in linked:
                raise ValueError(f'native callback missing from link: {target:08x}/{arity}')
print(f'Generated {len(targets)} native callback targets from {len(tables)} ROM descriptors; {rebased} resource relocations')
print(f'Rebased {len(curves)} original cutscene curve point arrays')
