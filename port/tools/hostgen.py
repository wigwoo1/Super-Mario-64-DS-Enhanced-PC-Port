def replace_bare_returns(text, class_name, method_name):
    """Make bare returns legal in reconstructed non-void host methods."""
    signature = re.compile(
        r"\b" + re.escape(class_name) + r"::" + re.escape(method_name) +
        r"\s*\([^)]*\)\s*\{")
    match = signature.search(text)
    if not match:
        return text, 0
    opening = text.find("{", match.start(), match.end())
    depth = 0
    closing = opening
    for closing in range(opening, len(text)):
        if text[closing] == "{":
            depth += 1
        elif text[closing] == "}":
            depth -= 1
            if depth == 0:
                break
    body = text[opening + 1:closing]
    body, count = re.subn(r"\breturn\s*;", "return 0;", body)
    return text[:opening + 1] + body + text[closing:], count


